"""Package only explicit project sources and the completed addon, never secrets/models."""
import argparse
import hashlib
from pathlib import Path
import shutil
import zipfile

ROOT = Path(__file__).resolve().parents[1]
SOURCE_DIRS = ('addon', 'data', 'docs', 'scripts', 'tests', 'tools')
SOURCE_FILES = ('.gitignore', 'README.md', 'THIRD_PARTY.md', 'requirements.txt',
                'requirements-dev.txt', 'requirements-lock.txt')


def source_files():
    for directory in SOURCE_DIRS:
        for path in sorted((ROOT / directory).rglob('*')):
            if path.is_file() and '__pycache__' not in path.parts and path.suffix != '.pyc':
                yield path
    for name in SOURCE_FILES:
        yield ROOT / name


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--addon', type=Path, default=ROOT / 'dist' / 'final' / 'AzerothVoz')
    args = parser.parse_args()
    install_zip = ROOT / 'dist' / 'AzerothVoz-0.1.0-12340.zip'
    source_zip = ROOT / 'dist' / 'AzerothVoz-0.1.0-fontes.zip'
    for path in (install_zip, source_zip):
        if path.exists():
            raise FileExistsError(f'Entrega já existe: {path}')
    # These copies update only outputs generated by this project, never a WoW install.
    (args.addon / 'docs').mkdir(exist_ok=True)
    for name in ('DIAGNOSTICO.md', 'TESTE-NO-JOGO.md', 'ENTREGA.md'):
        shutil.copyfile(ROOT / 'docs' / name, args.addon / 'docs' / name)
    with zipfile.ZipFile(install_zip, 'w', zipfile.ZIP_DEFLATED) as archive:
        for path in sorted(args.addon.rglob('*')):
            if path.is_file():
                archive.write(path, 'AzerothVoz/' + path.relative_to(args.addon).as_posix())
    with zipfile.ZipFile(source_zip, 'w', zipfile.ZIP_DEFLATED) as archive:
        for path in source_files():
            archive.write(path, 'AzerothVoz/' + path.relative_to(ROOT).as_posix())
    shutil.copytree(args.addon, ROOT / 'dist' / 'release' / 'AzerothVoz', dirs_exist_ok=True)
    sums = []
    for path in (install_zip, source_zip):
        checksum = hashlib.sha256(path.read_bytes()).hexdigest()
        sums.append(f'{checksum}  {path.name}')
        print(f'{path.name}: {path.stat().st_size} bytes')
    (ROOT / 'dist' / 'SHA256SUMS.txt').write_text('\n'.join(sums) + '\n', encoding='utf-8')


if __name__ == '__main__':
    main()
